// Draws the ten player avatars once, from DiceBear's Notionists style (art CC0, code MIT), and
// writes them as static files. The app never generates avatars at runtime.
//
//   node scripts/avatars.mjs
//
// Writes public/avatars/<id>.svg for the pages and src/features/card/avatar-art.ts (data URIs)
// for the share image, which renders on the server without fetching files. Re-run after changing
// a character below; the output is committed.

import { writeFileSync } from 'node:fs'

import { createAvatar } from '@dicebear/core'
import * as notionists from '@dicebear/notionists'

const props = (extra) => ({
  beardProbability: 0,
  glassesProbability: 0,
  gestureProbability: 0,
  bodyIconProbability: 0,
  ...extra,
})
const glasses = (variant) => ({ glasses: [variant], glassesProbability: 100 })
const gesture = (name) => ({ gesture: [name], gestureProbability: 100 })
const icon = (name) => ({ bodyIcon: [name], bodyIconProbability: 100 })

// id, seed (picks the body and face), hair, props. Higher unlocks earn more props.
const CHARACTERS = [
  ['dev-he', 'dev-he2', 'variant38', {}],
  ['dev-she', 'dev-she1', 'variant43', {}],
  ['reader', 'reader1', 'variant08', glasses('variant08')],
  ['spotter', 'spotter1', 'variant50', gesture('point')],
  ['reviewer', 'reviewer1', 'variant62', glasses('variant05')],
  ['oracle', 'oracle1', 'variant61', gesture('ok')],
  ['collector', 'collector0', 'variant47', icon('saturn')],
  ['night-owl', 'night-owl0', 'variant36', { ...glasses('variant08'), ...icon('electric') }],
  ['architect', 'architect1', 'variant22', { ...glasses('variant03'), ...icon('saturn') }],
  ['staff', 'staff1', 'variant56', { ...gesture('waveLongArm'), ...icon('galaxy') }],
]

const art = {}
for (const [id, seed, hair, extra] of CHARACTERS) {
  const svg = createAvatar(notionists, { seed, hair: [hair], ...props(extra) }).toString()
  writeFileSync(`public/avatars/${id}.svg`, svg)
  art[id] = `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`
}

const lines = Object.entries(art).map(([id, uri]) => `  '${id}': '${uri}',`)
writeFileSync(
  'src/features/card/avatar-art.ts',
  `// Generated by scripts/avatars.mjs. Do not edit by hand.\n// Avatar art as data URIs, for the share image rendered on the server.\n\nexport const AVATAR_ART: Readonly<Record<string, string>> = {\n${lines.join('\n')}\n}\n`,
)
console.log(`Wrote ${CHARACTERS.length} avatars.`)
